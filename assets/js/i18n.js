export function getLocale() {
  try { return JSON.parse(localStorage.getItem("maleta-settings") || "{}").uiLanguage === "en" ? "en" : "it"; }
  catch { return "it"; }
}

export function localeCode() { return getLocale() === "en" ? "en-GB" : "it-IT"; }

export function t(value) {
  if (getLocale() !== "en" || value == null) return value;
  const text = String(value);
  if (ENGLISH[text]) return ENGLISH[text];
  for (const [pattern, replacement] of PATTERNS) if (pattern.test(text)) return text.replace(pattern, replacement);
  return text;
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (!node.nodeValue.trim() || node.parentElement?.closest("[data-no-translate], [contenteditable=true]")) return;
    const leading = node.nodeValue.match(/^\s*/)?.[0] || "";
    const trailing = node.nodeValue.match(/\s*$/)?.[0] || "";
    const source = node.nodeValue.trim();
    const translated = t(source);
    if (translated !== source) node.nodeValue = `${leading}${translated}${trailing}`;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const attribute of ["aria-label", "placeholder", "title"]) {
    const source = node.getAttribute(attribute);
    if (source) node.setAttribute(attribute, t(source));
  }
  node.childNodes.forEach(translateNode);
}

let initialized = false;
export function initI18n() {
  document.documentElement.lang = getLocale();
  if (getLocale() !== "en") return;
  document.title = "Meleta — Lecture notes";
  translateNode(document.body);
  if (initialized) return;
  initialized = true;
  new MutationObserver((records) => records.forEach((record) => record.addedNodes.forEach(translateNode)))
    .observe(document.body, { childList: true, subtree: true });
  const nativeConfirm = window.confirm.bind(window);
  window.confirm = (message) => nativeConfirm(t(message));
}
